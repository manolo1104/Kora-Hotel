const DICTS: Record<Lang, Record<MsgKey, string>> = { es, en };

/** Traduce con interpolación {var}. `s` se resuelve solo: "" si n===1, plural si no. */
export function t(lang: Lang, key: MsgKey, vars?: Record<string, string | number>): string {
  let out: string = DICTS[lang][key] ?? es[key] ?? key;
  if (vars) {
    if (typeof vars.n === "number" && !("s" in vars)) {
      vars = { ...vars, s: vars.n === 1 ? "" : "s" };
    }
    for (const [k, v] of Object.entries(vars)) {
      out = out.replaceAll(`{${k}}`, String(v));
    }
  }
  return out;
}

export function localeOf(lang: Lang): string {
  return lang === "en" ? "en-US" : "es-MX";
}
